#!/usr/bin/env node
/**
 * Generate the white-label native environment file from CAP_* env vars + the
 * tenant manifest, so a bundled APK points at a real gateway instead of the
 * Capacitor WebView origin (`https://localhost`, which never reaches the API).
 *
 * Output: apps/web-angular/src/environments/environment.tenant-demo.ts
 *   -> consumed by the `tenant-demo` build configuration (fileReplacements).
 *
 * Usage:
 *   node scripts/gen-native-env.mjs
 *   $env:CAP_API_BASE_URL='http://192.168.1.20:8000'   # real device on LAN
 *   $env:CAP_TENANT_HOST='acme.example.com'            # tenant's registered host
 *   $env:CAP_TENANT='demo'
 *
 * Defaults: CAP_TENANT=demo, tenantHost=manifest canonicalHost, apiBaseUrl=
 * DEFAULT_NATIVE_API_BASE_URL (Android emulator loopback).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const manifestPath = path.join(
  root,
  'libs/shared/tenant-config/src/lib/tenants.manifest.ts',
);
const outPath = path.join(
  root,
  'apps/web-angular/src/environments/environment.tenant-demo.ts',
);

const manifestSource = readFileSync(manifestPath, 'utf8');
const { code } = esbuild.transformSync(manifestSource, {
  loader: 'ts',
  format: 'esm',
});
const manifest = await import(
  'data:text/javascript;base64,' + Buffer.from(code).toString('base64')
);

const tenantId = process.env.CAP_TENANT || manifest.TENANT_MANIFEST[0].id;
const tenant = manifest.findTenantManifest(tenantId);
const tenantHost =
  process.env.CAP_TENANT_HOST || tenant.canonicalHost || 'localhost';
const apiBaseUrl =
  process.env.CAP_API_BASE_URL ||
  tenant.apiBaseUrl ||
  manifest.DEFAULT_NATIVE_API_BASE_URL;

const contents = `import { AppEnvironment } from './environment.types';

/**
 * White-label build for the \`${tenant.id}\` tenant.
 *
 * AUTO-GENERATED by scripts/gen-native-env.mjs from CAP_* env vars and
 * tenants.manifest.ts. Committed with local defaults; re-run
 * \`npm run native:env\` (or any web:build:demo / web:sync:demo script) to
 * regenerate for a different gateway or device.
 */
export const environment: AppEnvironment = {
  production: true,
  defaultTenantId: ${JSON.stringify(tenant.id)},
  tenantHost: ${JSON.stringify(tenantHost)},
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
};
`;

writeFileSync(outPath, contents, 'utf8');
console.log(
  `[gen-native-env] ${path.relative(root, outPath)}\n` +
    `  tenant=${tenant.id} host=${tenantHost} apiBaseUrl=${apiBaseUrl || '(same-origin)'}`,
);
